export function createSupabasePool(config: SupabasePoolConfig): Pool {
  return new Pool({ ...config, ssl: { ca: SUPABASE_ROOT_CA } });
}

/** Reads pool config from discrete `SUPABASE_DB_*` env vars, or returns undefined if unset. */
export function supabasePoolConfigFromEnv(env: NodeJS.ProcessEnv = process.env): SupabasePoolConfig | undefined {
  const { SUPABASE_DB_HOST, SUPABASE_DB_USER, SUPABASE_DB_PASSWORD } = env;
  if (!SUPABASE_DB_HOST || !SUPABASE_DB_USER || !SUPABASE_DB_PASSWORD) {
    return undefined;
  }
  return {
    host: SUPABASE_DB_HOST,
    port: Number(env.SUPABASE_DB_PORT ?? 5432),
    user: SUPABASE_DB_USER,
    password: SUPABASE_DB_PASSWORD,
    database: env.SUPABASE_DB_NAME ?? "postgres",
  };
}
